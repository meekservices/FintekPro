// Helper to enrich raw holding with instrument registry info
function enrichHolding(h: { rank: number; name: string; category?: string; weight: number; symbol?: string; isin?: string | null; schemeCode?: number | null; type?: string; sector?: string }) {
  const inst = getInstrument(h.name);
  return {
    ...h,
    schemeCode: h.schemeCode ?? inst?.schemeCode ?? null,
    isin:       h.isin ?? inst?.isin ?? null,
    type:       h.type ?? inst?.type ?? "equity",
    amfiSchemeCode: h.schemeCode != null ? String(h.schemeCode) : (inst?.schemeCode != null ? String(inst.schemeCode) : null),
  };
}

