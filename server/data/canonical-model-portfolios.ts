/**
 * Resolves any portfolio ID (canonical or legacy alias) to its canonical portfolio representation.
 */
export function resolveCanonicalPortfolio(idOrAlias: string): CanonicalPortfolio | undefined {
  if (!idOrAlias) return undefined;
  const canonicalId = PORTFOLIO_ID_ALIASES[idOrAlias] ?? idOrAlias;
  return CANONICAL_PORTFOLIOS_BY_ID.get(canonicalId);
}
