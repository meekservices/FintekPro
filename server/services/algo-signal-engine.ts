// ─── Core Engine ─────────────────────────────────────────────────────────────

class AlgoSignalEngine {
	private readonly MODEL = MODEL_VERSION;

	/**
	 * Generate signals for a list of symbols.
	 * Persists results to algo_signals table.
	 *
	 * @param symbols      List of US ticker symbols (e.g. ["AAPL", "MSFT"])
	 * @param userId       FintekPro user ID (for per-user signals)
	 * @param riskProfile  User's risk tolerance
	 * @param horizon      Investment horizon
	 * @returns            Generated signal records (unsaved IDs — query DB after)
	 */
	async generateSignals(
		symbols: string[],
		userId: number,
		riskProfile: RiskProfile = "moderate",
		horizon: InvestmentHorizon = "medium",
	): Promise<SignalResult[]> {
		const startMs = Date.now();
		const upperSymbols = [
			...new Set(symbols.map((s) => s.toUpperCase())),
		].slice(0, 20); // cap at 20

		logger.info("[AlgoEngine] Generating signals", {
			userId,
			symbols: upperSymbols,
			riskProfile,
		});

		// Expire any stale pending signals for this user+symbols
		await this._expireStaleSignals(userId, upperSymbols);

		// Fetch 60 days of daily bars (needs SMA-50)
		const end = new Date();
		const start = new Date(end.getTime() - 65 * 24 * 60 * 60 * 1000);
		const barsMap = await alpacaMarketDataService.getBars(
			upperSymbols,
			"1Day",
			start.toISOString().split("T")[0],
			end.toISOString().split("T")[0],
			70,
		);

		const results: SignalResult[] = [];

		for (const symbol of upperSymbols) {
			try {
				const bars = barsMap.get(symbol) || [];
				if (bars.length < 21) {
					logger.warn(
						`[AlgoEngine] Insufficient bars for ${symbol}: ${bars.length}`,
					);
					continue;
				}

				const result = this._computeSignal(symbol, bars, riskProfile);
				if (!result) continue;

				// Persist to DB
				await db.insert(algoSignals).values({
					userId,
					symbol: result.symbol,
					strategy: result.strategy,
					signal: result.signal,
					confidenceScore: result.confidenceScore,
					suggestedNotional: String(result.suggestedNotional),
					entryPrice: String(result.entryPrice),
					targetPrice: String(result.targetPrice),
					stopLossPrice: String(result.stopLossPrice),
					factors: result.factors as any,
					modelVersion: result.modelVersion,
					riskProfile,
					investmentHorizon: horizon,
					status: "pending",
					disclaimer: result.disclaimer,
					expiresAt: result.expiresAt,
				});

				results.push(result);
			} catch (err: any) {
				logger.warn(`[AlgoEngine] Failed to compute signal for ${symbol}`, {
					error: err.message,
				});
			}
		}

		// Structured audit log (FASP-AI v1.0 requirement)
		await auditLog({
			action: "algo_signal_generated",
			category: "trading",
			outcome: results.length > 0 ? "success" : "failure",
			riskLevel: "low",
			details: {
				event: "ALGO_SIGNAL_GENERATED",
				user_id: userId,
				input_context: { symbols: upperSymbols, riskProfile, horizon },
				output_summary: {
					generated: results.length,
					signals: results.map((r) => ({
						symbol: r.symbol,
						signal: r.signal,
						confidence: r.confidenceScore,
					})),
				},
				model_version: this.MODEL,
				latency_ms: Date.now() - startMs,
				timestamp: new Date().toISOString(),
			},
		}).catch(() => {});

		return results;
	}

	/**
	 * List signals for a user with optional filters.
	 */
	async listSignals(
		userId: number,
		filters: {
			status?: string;
			symbol?: string;
			limit?: number;
			page?: number;
		} = {},
	) {
		const { status, symbol, limit = 20, page = 1 } = filters;
		const offset = (page - 1) * limit;

		const conditions = [eq(algoSignals.userId, userId)];
		if (status) conditions.push(eq(algoSignals.status, status));
		if (symbol) conditions.push(eq(algoSignals.symbol, symbol.toUpperCase()));

		const rows = await db
			.select()
			.from(algoSignals)
			.where(and(...conditions))
			// BUG-ALGO-2 FIX: orderBy DESC in SQL so page N is correctly ordered.
			// Previous code used orderBy ASC + in-memory .sort() DESC after .limit(),
			// which reversed only the current page — pages 2+ were wrong relative to page 1.
			.orderBy(desc(algoSignals.createdAt))
			.limit(limit)
			.offset(offset);

		return rows;
	}

	/**
	 * Approve a signal — mark as approved and optionally link an order ID.
	 */
	async approveSignal(signalId: number, userId: number, orderId?: string) {
		const [updated] = await db
			.update(algoSignals)
			.set({
				status: "approved",
				approvedAt: new Date(),
				orderId: orderId || null,
				updatedAt: new Date(),
			})
			.where(and(eq(algoSignals.id, signalId), eq(algoSignals.userId, userId)))
			.returning();

		if (!updated) throw new Error("Signal not found or not owned by user");

		await auditLog({
			action: "algo_signal_approved",
			category: "trading",
			outcome: "success",
			riskLevel: "medium",
			details: {
				event: "ALGO_SIGNAL_APPROVED",
				user_id: userId,
				signal_id: signalId,
				symbol: updated.symbol,
				signal: updated.signal,
				confidence: updated.confidenceScore,
				order_id: orderId,
				model_version: updated.modelVersion,
				timestamp: new Date().toISOString(),
			},
		}).catch(() => {});

		return updated;
	}

	/**
	 * Reject a signal — mark as rejected.
	 */
	async rejectSignal(signalId: number, userId: number) {
		const [updated] = await db
			.update(algoSignals)
			.set({
				status: "rejected",
				rejectedAt: new Date(),
				updatedAt: new Date(),
			})
			.where(and(eq(algoSignals.id, signalId), eq(algoSignals.userId, userId)))
			.returning();

		if (!updated) throw new Error("Signal not found or not owned by user");

		await auditLog({
			action: "algo_signal_rejected",
			category: "trading",
			outcome: "success",
			riskLevel: "low",
			details: {
				event: "ALGO_SIGNAL_REJECTED",
				user_id: userId,
				signal_id: signalId,
				symbol: updated.symbol,
				timestamp: new Date().toISOString(),
			},
		}).catch(() => {});

		return updated;
	}

	/**
	 * Performance: count signal outcomes for a user using SQL aggregation.
	 * BUG-ALGO-1 FIX: was a full table scan + 4× in-memory Array.filter().
	 * Now uses a single COUNT(*) FILTER query — O(1) DB cost regardless of history size.
	 */
	async getPerformance(userId: number) {
		// One SQL query — all aggregates in the DB
		const [row] = await db
			.select({
				total:         sql<number>`COUNT(*)::int`,
				approved:      sql<number>`COUNT(*) FILTER (WHERE status = 'approved')::int`,
				rejected:      sql<number>`COUNT(*) FILTER (WHERE status = 'rejected')::int`,
				pending:       sql<number>`COUNT(*) FILTER (WHERE status = 'pending')::int`,
				expired:       sql<number>`COUNT(*) FILTER (WHERE status = 'expired')::int`,
				buy_count:     sql<number>`COUNT(*) FILTER (WHERE signal = 'buy')::int`,
				sell_count:    sql<number>`COUNT(*) FILTER (WHERE signal = 'sell')::int`,
				watch_count:   sql<number>`COUNT(*) FILTER (WHERE signal = 'watch')::int`,
				hold_count:    sql<number>`COUNT(*) FILTER (WHERE signal = 'hold')::int`,
				avg_confidence: sql<number>`ROUND(AVG(confidence_score))::int`,
			})
			.from(algoSignals)
			.where(eq(algoSignals.userId, userId));

		return {
			total:         row.total,
			approved:      row.approved,
			rejected:      row.rejected,
			pending:       row.pending,
			expired:       row.expired,
			bySignal: {
				buy:   row.buy_count,
				sell:  row.sell_count,
				watch: row.watch_count,
				hold:  row.hold_count,
			},
			avgConfidence: row.avg_confidence ?? 0,
		};
	}

	// ─── Private: Core Signal Computation ──────────────────────────────────────

	private _computeSignal(
		symbol: string,
		bars: Array<{ c: number; h: number; l: number; v: number }>,
		riskProfile: RiskProfile,
	): SignalResult | null {
		if (bars.length < 21) return null;

		const closes = bars.map((b) => b.c);
		const highs = bars.map((b) => b.h);
		const lows = bars.map((b) => b.l);
		const volumes = bars.map((b) => b.v);

		const currentPrice = closes[closes.length - 1];

		// ── SMA calculations ────────────────────────────────────────────────────
		const sma20 = this._sma(closes, 20);
		const sma50 = bars.length >= 50 ? this._sma(closes, 50) : sma20;

		// ── RSI(14) ─────────────────────────────────────────────────────────────
		const rsi14 = this._rsi(closes, 14);

		// ── Volume ratio (5d avg / 20d avg) ─────────────────────────────────────
		const vol5 = this._sma(volumes, 5);
		const vol20 = this._sma(volumes, 20);
		const volumeRatio = vol20 > 0 ? +(vol5 / vol20).toFixed(3) : 1;

		// ── 20-day momentum (%) ─────────────────────────────────────────────────
		const price20dAgo = closes[Math.max(0, closes.length - 21)];
		const momentum20d =
			price20dAgo > 0
				? +(((currentPrice - price20dAgo) / price20dAgo) * 100).toFixed(2)
				: 0;

		// ── 20-day high/low ──────────────────────────────────────────────────────
		const recent20h = highs.slice(-20);
		const recent20l = lows.slice(-20);
		const high20d = Math.max(...recent20h);
		const low20d = Math.min(...recent20l);

		// ── ATR(14) — for target/stop sizing ─────────────────────────────────────
		const atr14 = this._atr(highs, lows, closes, 14);

		// ── Strategy scores (-1 = strong sell, 0 = neutral, +1 = strong buy) ────

		// SMA Crossover: SMA20 vs SMA50
		const smaDiff = sma50 > 0 ? (sma20 - sma50) / sma50 : 0;
		const smaScore = Math.max(-1, Math.min(1, smaDiff * 20)); // scale: 5% diff → ±1

		// RSI Mean Reversion
		let rsiScore = 0;
		if (rsi14 < 30)
			rsiScore = +(1 - rsi14 / 30).toFixed(3); // oversold → buy
		else if (rsi14 > 70) rsiScore = -((rsi14 - 70) / 30).toFixed(3); // overbought → sell

		// Momentum + Volume confirmation
		const momentumRaw = Math.max(-1, Math.min(1, momentum20d / 15)); // 15% → ±1
		const volBoost = volumeRatio > 1.3 ? 1.2 : volumeRatio < 0.7 ? 0.8 : 1.0;
		const momentumScore = +(momentumRaw * volBoost).toFixed(3);

		// ── Composite confidence ─────────────────────────────────────────────────
		// Weights: SMA=40%, RSI=30%, Momentum=30%
		const compositeRaw = smaScore * 0.4 + rsiScore * 0.3 + momentumScore * 0.3;
		const confidenceScore = Math.round(
			Math.min(100, Math.abs(compositeRaw) * 100),
		);
		const direction = compositeRaw >= 0 ? "buy" : "sell";

		// FASP-AI v1.0: downgrade low-confidence signals
		let signal: "buy" | "sell" | "watch" | "hold";
		if (confidenceScore < 40) {
			signal = "hold";
		} else if (confidenceScore < 60) {
			signal = "watch"; // no actionable direction
		} else {
			signal = direction;
		}

		// ── Price levels ─────────────────────────────────────────────────────────
		const atrMultiplier =
			riskProfile === "conservative"
				? 1.0
				: riskProfile === "aggressive"
					? 2.0
					: 1.5;
		const entryPrice = +currentPrice.toFixed(4);
		const targetPrice =
			signal === "buy"
				? +(currentPrice + atr14 * atrMultiplier * 2).toFixed(4)
				: +(currentPrice - atr14 * atrMultiplier * 2).toFixed(4);
		const stopLossPrice =
			signal === "buy"
				? +(currentPrice - atr14 * atrMultiplier).toFixed(4)
				: +(currentPrice + atr14 * atrMultiplier).toFixed(4);

		const suggestedNotional = NOTIONAL_BY_RISK[riskProfile];

		// NYSE close (4 PM ET = 21:30 UTC) today
		const expiresAt = new Date();
		expiresAt.setUTCHours(21, 30, 0, 0);
		if (expiresAt.getTime() < Date.now())
			expiresAt.setDate(expiresAt.getDate() + 1);

		const factors: SignalFactors = {
			currentPrice,
			sma20: +sma20.toFixed(4),
			sma50: +sma50.toFixed(4),
			rsi14: +rsi14.toFixed(2),
			volumeRatio,
			momentum20d,
			high20d: +high20d.toFixed(4),
			low20d: +low20d.toFixed(4),
			atr14: +atr14.toFixed(4),
			smaScore: +smaScore.toFixed(3),
			rsiScore: +rsiScore.toFixed(3),
			momentumScore: +momentumScore.toFixed(3),
		};

		return {
			symbol,
			strategy: "composite",
			signal,
			confidenceScore,
			entryPrice,
			targetPrice,
			stopLossPrice,
			suggestedNotional,
			factors,
			modelVersion: this.MODEL,
			disclaimer: DISCLAIMER,
			expiresAt,
		};
	}

	// ─── Maths helpers ──────────────────────────────────────────────────────────

	private _sma(arr: number[], period: number): number {
		const slice = arr.slice(-period);
		if (slice.length === 0) return 0;
		return slice.reduce((a, b) => a + b, 0) / slice.length;
	}

	private _rsi(closes: number[], period: number): number {
		if (closes.length < period + 1) return 50;
		let gains = 0,
			losses = 0;
		for (let i = closes.length - period; i < closes.length; i++) {
			const diff = closes[i] - closes[i - 1];
			if (diff >= 0) gains += diff;
			else losses -= diff;
		}
		const avgGain = gains / period;
		const avgLoss = losses / period;
		if (avgLoss === 0) return 100;
		const rs = avgGain / avgLoss;
		return +(100 - 100 / (1 + rs)).toFixed(2);
	}

	private _atr(
		highs: number[],
		lows: number[],
		closes: number[],
		period: number,
	): number {
		const trs: number[] = [];
		for (let i = 1; i < highs.length; i++) {
			const tr = Math.max(
				highs[i] - lows[i],
				Math.abs(highs[i] - closes[i - 1]),
				Math.abs(lows[i] - closes[i - 1]),
			);
			trs.push(tr);
		}
		return this._sma(trs, period);
	}

	private async _expireStaleSignals(userId: number, symbols: string[]) {
		// Mark old pending signals for these symbols as expired
		await db
			.update(algoSignals)
			.set({ status: "expired", updatedAt: new Date() })
			.where(
				and(
					eq(algoSignals.userId, userId),
					eq(algoSignals.status, "pending"),
					inArray(algoSignals.symbol, symbols),
				),
			)
			.catch(() => {}); // non-fatal
	}
}

