// ─── Types ───────────────────────────────────────────────────────────────────

export interface SignalFactors {
	currentPrice: number;
	sma20: number;
	sma50: number;
	rsi14: number;
	volumeRatio: number; // current 5d avg volume / 20d avg volume
	momentum20d: number; // % price change over 20 days
	high20d: number;
	low20d: number;
	atr14: number; // Average True Range — used for target/stop calc
	// individual strategy scores
	smaScore: number; // -1 to +1
	rsiScore: number; // -1 to +1
	momentumScore: number; // -1 to +1
}

export interface SignalResult {
	symbol: string;
	companyName?: string;
	strategy: string;
	signal: "buy" | "sell" | "watch" | "hold";
	confidenceScore: number; // 0–100
	entryPrice: number;
	targetPrice: number;
	stopLossPrice: number;
	suggestedNotional: number; // USD, risk-based sizing
	factors: SignalFactors;
	modelVersion: string;
	disclaimer: string;
	expiresAt: Date;
}

export type RiskProfile =
	| "conservative"
	| "moderate"
	| "aggressive"
	| "very_aggressive";
export type InvestmentHorizon = "short" | "medium" | "long";

